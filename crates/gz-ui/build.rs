//! Generates the theme and icon code from the spec's data files
//! (`design/ui/`), so a token or icon edit can't drift from the code:
//!
//! - `tokens.rs` from `tokens.json`: `Palette` (light and dark), `ColorRole`,
//!   `Sizes`, `SPACE`, radii, borders, motion, elevation and the type styles
//!   (DECISIONS.md D-21). Included by `src/theme/tokens.rs`.
//! - `icons.rs` from `icons.json`: the `IconId` enum. Included by
//!   `src/assets/icons/mod.rs`.
//! - `icons@1x.png`, `icons@2x.png`: every icon at every size in
//!   `layout::SIZES`, white on transparent, rasterized with resvg (build
//!   time only, so resvg stays out of the wasm payload). Embedded with
//!   `include_bytes!`. Every texel is white, transparent ones included, so
//!   filtering at the glyph edges can't blend toward black.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde_json::{Map, Value};

#[allow(dead_code)]
#[path = "src/assets/icons/layout.rs"]
mod layout;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets it"));
    let design = manifest.join("../../design/ui");
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets it"));
    let tokens_path = design.join("tokens.json");
    let icons_path = design.join("icons.json");
    println!("cargo:rerun-if-changed={}", tokens_path.display());
    println!("cargo:rerun-if-changed={}", icons_path.display());
    println!("cargo:rerun-if-changed=src/assets/icons/layout.rs");

    let tokens = read_json(&tokens_path);
    write(&out.join("tokens.rs"), &tokens_rs(&tokens));

    let icons = read_json(&icons_path);
    let icons = icon_list(&icons);
    write(&out.join("icons.rs"), &icons_rs(&icons));
    for scale in [1, 2] {
        save_white_png(
            &atlas(&icons, scale),
            &out.join(format!("icons@{scale}x.png")),
        );
    }
}

fn read_json(path: &Path) -> Value {
    let text =
        std::fs::read_to_string(path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    serde_json::from_str(&text).unwrap_or_else(|e| panic!("parse {}: {e}", path.display()))
}

fn write(path: &Path, text: &str) {
    std::fs::write(path, text).unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
}

fn obj<'a>(v: &'a Value, key: &str) -> &'a Map<String, Value> {
    v.get(key)
        .and_then(Value::as_object)
        .unwrap_or_else(|| panic!("tokens.json: `{key}` is not an object"))
}

fn num(v: &Value) -> f64 {
    v.as_f64()
        .unwrap_or_else(|| panic!("expected a number, got {v}"))
}

/// `snake_case` → `CamelCase`; digits stay (`text_2` → `Text2`).
fn camel(name: &str) -> String {
    name.split('_')
        .map(|part| {
            let mut c = part.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

fn float(v: f64) -> String {
    format!("{v:?}_f32").replace(".0_f32", ".0")
}

/// `#RRGGBB` or `#RRGGBBAA` → `(r, g, b, a)`.
fn hex(s: &str) -> (u8, u8, u8, u8) {
    let h = s.strip_prefix('#').unwrap_or_else(|| panic!("colour {s}"));
    let byte =
        |i: usize| u8::from_str_radix(&h[i..i + 2], 16).unwrap_or_else(|e| panic!("{s}: {e}"));
    match h.len() {
        6 => (byte(0), byte(2), byte(4), 255),
        8 => (byte(0), byte(2), byte(4), byte(6)),
        _ => panic!("colour {s}: expected #RRGGBB or #RRGGBBAA"),
    }
}

fn tokens_rs(t: &Value) -> String {
    let mut s =
        String::from("// @generated by build.rs from design/ui/tokens.json. Do not edit.\n\n");
    let colors = &t["color"];
    let light = obj(colors, "light");
    let dark = obj(colors, "dark");
    let names: Vec<&String> = light.keys().collect();
    let dark_names: Vec<&String> = dark.keys().collect();
    assert_eq!(
        names, dark_names,
        "tokens.json: light and dark colour tokens differ"
    );

    // Palette.
    s += "/// Every colour token, resolved for one theme. Field names are the\n";
    s += "/// `tokens.json` keys.\n";
    s += "#[derive(Clone, Debug, PartialEq, Reflect)]\npub struct Palette {\n";
    for n in &names {
        let _ = writeln!(s, "    /// `{n}`\n    pub {n}: Color,");
    }
    s += "}\n\nimpl Palette {\n";
    for (theme, map) in [("light", light), ("dark", dark)] {
        let _ = writeln!(
            s,
            "    /// The `{theme}` colours.\n    pub fn {theme}() -> Self {{\n        Self {{"
        );
        for n in &names {
            let (r, g, b, a) = hex(map[n.as_str()].as_str().expect("colour string"));
            let _ = writeln!(s, "            {n}: Color::srgba_u8({r}, {g}, {b}, {a}),");
        }
        s += "        }\n    }\n\n";
    }
    s += "    /// The colour a role resolves to.\n    pub fn role(&self, role: ColorRole) -> Color {\n        match role {\n";
    for n in &names {
        let _ = writeln!(s, "            ColorRole::{} => self.{n},", camel(n));
    }
    s += "            ColorRole::Clear => Color::NONE,\n        }\n    }\n}\n\n";

    // ColorRole.
    s += "/// A semantic colour: every `tokens.json` colour token, plus [`ColorRole::Clear`].\n";
    s += "/// Widgets store roles ([`Fill`], [`Stroke`], [`Ink`], …), never a resolved\n";
    s += "/// colour, so a theme switch only re-resolves them.\n";
    s += "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Reflect)]\npub enum ColorRole {\n";
    for n in &names {
        let _ = writeln!(s, "    /// `{n}`\n    {},", camel(n));
    }
    s += "    /// Fully transparent (not a token).\n    Clear,\n}\n\n";
    let _ = writeln!(s, "impl ColorRole {{\n    /// Every token role, in `tokens.json` order (not [`ColorRole::Clear`]).\n    pub const TOKENS: [ColorRole; {}] = [", names.len());
    for n in &names {
        let _ = writeln!(s, "        ColorRole::{},", camel(n));
    }
    s += "    ];\n\n    /// The `tokens.json` key, or `None` for [`ColorRole::Clear`].\n    pub fn token(self) -> Option<&'static str> {\n        Some(match self {\n";
    for n in &names {
        let _ = writeln!(s, "            ColorRole::{} => \"{n}\",", camel(n));
    }
    s += "            ColorRole::Clear => return None,\n        })\n    }\n}\n\n";

    // Sizes.
    let sizes = obj(t, "size");
    s += "/// Fixed sizes in logical pixels (`tokens.json` `size`).\n";
    s += "#[derive(Clone, Debug, PartialEq, Reflect)]\npub struct Sizes {\n";
    for (n, _) in sizes {
        let _ = writeln!(s, "    /// `{n}`\n    pub {n}: f32,");
    }
    s += "}\n\nimpl Default for Sizes {\n    fn default() -> Self {\n        Self {\n";
    for (n, v) in sizes {
        let _ = writeln!(s, "            {n}: {},", float(num(v)));
    }
    s += "        }\n    }\n}\n\n";

    // Spacing.
    let space = obj(t, "space");
    let mut steps: Vec<(usize, f64)> = space
        .iter()
        .map(|(k, v)| (k.parse().expect("space keys are 1..=N"), num(v)))
        .collect();
    steps.sort_by_key(|(k, _)| *k);
    for (i, (k, _)) in steps.iter().enumerate() {
        assert_eq!(*k, i + 1, "tokens.json: space keys must be 1..=N");
    }
    let _ = write!(
        s,
        "/// Spacing scale (`tokens.json` `space`): `SPACE[n]` is step `n`; `SPACE[0]` is 0.\npub const SPACE: [f32; {}] = [0.0",
        steps.len() + 1
    );
    for (_, v) in &steps {
        let _ = write!(s, ", {}", float(*v));
    }
    s += "];\n\n";

    // Radii and borders. Each module also lists its entries in `ALL`, so a
    // test can walk tokens.json against them.
    for (key, module, doc) in [
        ("radius", "radius", "Corner radii"),
        ("border", "border", "Border widths"),
    ] {
        let _ = writeln!(s, "/// {doc} (`tokens.json` `{key}`).\npub mod {module} {{");
        let entries = obj(t, key);
        for (n, v) in entries {
            let _ = writeln!(
                s,
                "    /// `{n}`\n    pub const {}: f32 = {};",
                n.to_ascii_uppercase(),
                float(num(v))
            );
        }
        all(&mut s, "f32", entries.keys());
        s += "}\n\n";
    }

    // Motion: durations (numbers, `_ms`) and the easing and reduce-motion
    // rules (strings); anything else is an error rather than skipped.
    s += "/// Durations in milliseconds and the motion rules (`tokens.json` `motion`).\npub mod motion {\n";
    let motion = obj(t, "motion");
    let mut durations = Vec::new();
    for (n, v) in motion {
        let name = n.to_ascii_uppercase();
        match (v.as_f64(), v.as_str()) {
            (Some(ms), _) if n.ends_with("_ms") => {
                let _ = writeln!(
                    s,
                    "    /// `{n}`\n    pub const {name}: f32 = {};",
                    float(ms)
                );
                durations.push(n);
            }
            (None, Some(text)) if !n.ends_with("_ms") => {
                let _ = writeln!(s, "    /// `{n}`\n    pub const {name}: &str = {text:?};");
            }
            _ => panic!("tokens.json: motion.{n} = {v}: durations end in _ms, rules are strings"),
        }
    }
    all(&mut s, "f32", durations.into_iter());
    s += "}\n\n";

    // Elevation: a shadow `y` below, blurred by `blur`, in the `color`
    // token (none: no shadow).
    s += "/// Shadows (`tokens.json` `elevation`).\npub mod elevation {\n    use super::{ColorRole, Elevation};\n";
    let elevations = obj(t, "elevation");
    for (n, v) in elevations {
        let color = match v.get("color").map(|c| c.as_str()) {
            None => "None".to_string(),
            Some(Some(c)) if light.contains_key(c) => format!("Some(ColorRole::{})", camel(c)),
            Some(c) => panic!("tokens.json: elevation.{n}.color {c:?} is not a colour token"),
        };
        let _ = writeln!(
            s,
            "    /// `{n}`\n    pub const {}: Elevation = Elevation {{ blur: {}, y: {}, color: {color} }};",
            n.to_ascii_uppercase(),
            float(num(&v["blur"])),
            float(num(&v["y"]))
        );
    }
    all(&mut s, "Elevation", elevations.keys());
    s += "}\n\n";

    // Type styles.
    s += "impl TypeStyle {\n";
    for (n, v) in obj(t, "type") {
        let font = match v["font"].as_str() {
            Some("ui") => "FontFamily::Ui",
            Some("mono") => "FontFamily::Mono",
            other => panic!("type.{n}: unknown font {other:?}"),
        };
        let note = v
            .get("note")
            .and_then(Value::as_str)
            .map(|n| format!(" ({n})"))
            .unwrap_or_default();
        let _ = writeln!(
            s,
            "    /// `{n}`{note}\n    pub const {}: TypeStyle = TypeStyle {{ font: {font}, size: {}, weight: {}, uppercase: {}, tracking: {} }};",
            n.to_ascii_uppercase(),
            float(num(&v["size"])),
            num(&v["weight"]) as u16,
            v.get("uppercase").and_then(Value::as_bool).unwrap_or(false),
            float(v.get("tracking").map(num).unwrap_or(0.0)),
        );
    }
    s += "}\n";
    s
}

/// `pub const ALL: [(&str, ty); N]`: every entry of a token module by its
/// `tokens.json` name.
fn all<'a>(s: &mut String, ty: &str, names: impl ExactSizeIterator<Item = &'a String>) {
    let _ = writeln!(
        s,
        "    /// Every entry, by its `tokens.json` name.\n    pub const ALL: [(&str, {ty}); {}] = [",
        names.len()
    );
    for n in names {
        let _ = writeln!(s, "        (\"{n}\", {}),", n.to_ascii_uppercase());
    }
    s.push_str("    ];\n");
}

/// One icon from icons.json.
struct Icon {
    name: String,
    svg: String,
}

fn icon_list(v: &Value) -> Vec<Icon> {
    let width = num(&v["stroke_width"]);
    let icons = obj(v, "icons");
    icons
        .iter()
        .map(|(name, def)| Icon {
            name: name.clone(),
            svg: icon_svg(name, def, width),
        })
        .collect()
}

fn dash_attr(v: Option<&Value>) -> String {
    v.and_then(Value::as_array)
        .map(|d| {
            let d: Vec<String> = d.iter().map(|x| num(x).to_string()).collect();
            format!(r#" stroke-dasharray="{}""#, d.join(" "))
        })
        .unwrap_or_default()
}

/// The icon as an SVG document, white on transparent. icons.json `$note`:
/// viewBox 24, stroke 1.75 with round caps and joins and no fill, unless
/// `fill` is true: then filled with no stroke (DECISIONS.md D-24).
fn icon_svg(name: &str, def: &Value, width: f64) -> String {
    let filled = def.get("fill").and_then(Value::as_bool).unwrap_or(false);
    let paint = if filled {
        r##"fill="#ffffff" stroke="none""##.to_string()
    } else {
        format!(
            r##"fill="none" stroke="#ffffff" stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round""##
        )
    };
    let mut body = String::new();
    let list = |key: &str| {
        def.get(key)
            .and_then(Value::as_array)
            .cloned()
            .unwrap_or_default()
    };
    for p in list("paths") {
        let d = p
            .as_str()
            .unwrap_or_else(|| panic!("{name}: path is not a string"));
        let _ = write!(body, r#"<path d="{d}"/>"#);
    }
    for r in list("rects") {
        let _ = write!(
            body,
            r#"<rect x="{}" y="{}" width="{}" height="{}" rx="{}"{}/>"#,
            num(&r["x"]),
            num(&r["y"]),
            num(&r["w"]),
            num(&r["h"]),
            r.get("rx").map(num).unwrap_or(0.0),
            dash_attr(r.get("dash"))
        );
    }
    for c in list("circles") {
        let _ = write!(
            body,
            r#"<circle cx="{}" cy="{}" r="{}"/>"#,
            num(&c["cx"]),
            num(&c["cy"]),
            num(&c["r"])
        );
    }
    for e in list("ellipses") {
        let _ = write!(
            body,
            r#"<ellipse cx="{}" cy="{}" rx="{}" ry="{}"/>"#,
            num(&e["cx"]),
            num(&e["cy"]),
            num(&e["rx"]),
            num(&e["ry"])
        );
    }
    assert!(!body.is_empty(), "icons.json: {name} has no shapes");
    format!(
        r#"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24"><g {paint}{}>{body}</g></svg>"#,
        dash_attr(def.get("dash"))
    )
}

fn icons_rs(icons: &[Icon]) -> String {
    let mut s =
        String::from("// @generated by build.rs from design/ui/icons.json. Do not edit.\n\n");
    s += "/// Every icon in `icons.json`, in file order.\n";
    s += "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Reflect)]\npub enum IconId {\n";
    for i in icons {
        let _ = writeln!(s, "    /// `{}`\n    {},", i.name, camel(&i.name));
    }
    let _ = writeln!(s, "}}\n\nimpl IconId {{\n    /// Every icon, in atlas order.\n    pub const ALL: [IconId; {}] = [", icons.len());
    for i in icons {
        let _ = writeln!(s, "        IconId::{},", camel(&i.name));
    }
    s += "    ];\n\n    /// The `icons.json` key.\n    pub fn name(self) -> &'static str {\n        match self {\n";
    for i in icons {
        let _ = writeln!(
            s,
            "            IconId::{} => \"{}\",",
            camel(&i.name),
            i.name
        );
    }
    s += "        }\n    }\n}\n";
    s
}

/// Writes `pixmap` (white glyphs, premultiplied) as straight-alpha RGBA
/// with every texel's colour white: the alpha holds the whole glyph.
/// Bevy samples straight alpha, and a transparent black texel next to an
/// edge would darken it under linear filtering.
fn save_white_png(pixmap: &tiny_skia::Pixmap, path: &Path) {
    let data: Vec<u8> = pixmap
        .pixels()
        .iter()
        .flat_map(|p| [255, 255, 255, p.alpha()])
        .collect();
    let file =
        std::fs::File::create(path).unwrap_or_else(|e| panic!("create {}: {e}", path.display()));
    let mut encoder = png::Encoder::new(
        std::io::BufWriter::new(file),
        pixmap.width(),
        pixmap.height(),
    );
    encoder.set_color(png::ColorType::Rgba);
    encoder.set_depth(png::BitDepth::Eight);
    encoder
        .write_header()
        .and_then(|mut w| w.write_image_data(&data))
        .unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
}

fn atlas(icons: &[Icon], scale: u32) -> tiny_skia::Pixmap {
    let count = icons.len() as u32;
    let (w, h) = layout::atlas_size(scale, count);
    let mut pixmap = tiny_skia::Pixmap::new(w, h).expect("atlas size is non-zero");
    let options = resvg::usvg::Options::default();
    for (index, icon) in icons.iter().enumerate() {
        let tree = resvg::usvg::Tree::from_str(&icon.svg, &options)
            .unwrap_or_else(|e| panic!("icons.json: {}: {e}", icon.name));
        for size_index in 0..layout::SIZES.len() {
            let (x, y, side) = layout::cell(scale, size_index, index as u32, count);
            let k = side as f32 / 24.0;
            let transform =
                tiny_skia::Transform::from_scale(k, k).post_translate(x as f32, y as f32);
            resvg::render(&tree, transform, &mut pixmap.as_mut());
        }
    }
    pixmap
}
